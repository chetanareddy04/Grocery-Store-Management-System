-- CUSTOMER INSIGHTS

--  1.How many unique customers have placed orders?
SELECT COUNT(DISTINCT cust_id) AS unique_customers
FROM orders;

-- 2.Which customers have placed the highest number of orders?
WITH customer_ranking AS( 
SELECT  cust.cust_id,cust.cust_name,
COUNT(ord.ord_id) as no_of_orders,
RANK() OVER(ORDER BY COUNT(ord.ord_id)DESC) AS orders_rank
FROM customers as cust
JOIN orders as ord
ON cust.cust_id=ord.cust_id
GROUP BY cust.cust_id,cust.cust_name)
SELECT cust_id,cust_name,no_of_orders,orders_rank
FROM customer_ranking
WHERE orders_rank=1;

-- 3. What is the total and average purchase value per customer?
SELECT 
    ord.cust_id,
    cust.cust_name,
    SUM(ord_det.total_price) as total_purchase_val,
    AVG(ord_det.total_price) as avg_purchase_val
FROM orders as ord
JOIN customers as cust
ON ord.cust_id=cust.cust_id
JOIN orderdetails as ord_det
    ON ord.ord_id = ord_det.ord_id
GROUP BY ord.cust_id,cust.cust_name;

-- 4. Who are the top 5 customers by total purchase amount?
SELECT 
    cust_id,
    cust_name,
    (SELECT 
            SUM(ord_det.total_price)
        FROM
            orders AS ord
                JOIN
            orderdetails AS ord_det ON ord.ord_id = ord_det.ord_id
        WHERE
            ord.cust_id = cust.cust_id) AS total_purchase_amount
FROM
    customers AS cust
ORDER BY total_purchase_amount DESC
LIMIT 5;

-- PRODUCT PERFORMANCE --

-- 5.How many products exist in each category?
SELECT 
    cat.cat_id, cat.cat_name, COUNT(prod_id) AS total_products
FROM
    categories AS cat
        JOIN
    products AS prod ON cat.cat_id = prod.cat_id
GROUP BY cat.cat_id , cat.cat_name;

--  6.What is the average price of products by category?
SELECT 
     cat_id,
	 ( SELECT cat_name
     FROM categories
     WHERE categories.cat_id=products.cat_id) as cat_name,
     AVG(price) as avg_price
FROM products
GROUP BY cat_id;

-- 7.Which products have the highest total sales volume (by quantity)?
SELECT prod.prod_id,prod.prod_name,SUM(ord_det.quantity) AS
total_sales_quantity,
DENSE_RANK() OVER(ORDER BY SUM(ord_det.quantity) DESC) AS sales_rank
FROM products as prod
JOIN orderdetails as ord_det
ON prod.prod_id=ord_det.prod_id
GROUP BY prod.prod_id,prod.prod_name
HAVING SUM(ord_det.quantity)=(SELECT MAX(total_quantity)
FROM (SELECT SUM(quantity) AS total_quantity
FROM orderdetails
GROUP BY prod_id)AS product_sales
);

-- 8.What is the total revenue generated by each product?
SELECT prod_id,SUM(total_price) as total_revenue
FROM orderdetails
GROUP BY prod_id;

-- 9.How do product sales vary by category and supplier?
CREATE VIEW category_supplier_sales AS
SELECT
    prod.cat_id,
    prod.sup_id,
    SUM(ord_det.total_price) AS total_sales
FROM products AS prod
JOIN orderdetails AS ord_det
    ON prod.prod_id = ord_det.prod_id
GROUP BY prod.cat_id, prod.sup_id;
SELECT *
FROM category_supplier_sales
ORDER BY total_sales DESC;


-- SALES AND OTHER TRENDS

-- 10.How many orders have been placed in total?
SELECT COUNT(ord_id) as total_orders
FROM orders;

-- 11.What is the average value per order?

SELECT AVG(ord_total) as avg_order_value
FROM (
SELECT ord_id,SUM( total_price) as ord_total
FROM orderdetails
GROUP BY ord_id)
AS order_values;

-- 12.On which dates were the most orders placed?
SELECT
    order_date,
    total_orders
FROM (
    SELECT
        order_date,
        COUNT(ord_id) AS total_orders,
        MAX(COUNT(ord_id)) OVER () AS highest_orders
    FROM orders
    GROUP BY order_date
) AS daily_orders
WHERE total_orders = highest_orders;

-- 13.What are the monthly trends in order volume and revenue?
SELECT 
    DATE_FORMAT(STR_TO_DATE(order_date, '%m/%d/%Y'),
            '%m') AS month,
    COUNT(orders.ord_id) AS order_volume,
    SUM(orderdetails.total_price) AS revenue
FROM
    orders
        JOIN
    orderdetails ON orders.ord_id = orderdetails.ord_id
GROUP BY month
ORDER BY month;

-- 14.How do order patterns vary across weekdays and weekends?
SELECT
    CASE
        WHEN DAYOFWEEK(STR_TO_DATE(order_date, '%m/%d/%Y')) IN (1, 7)
            THEN 'Weekend'
        ELSE 'Weekday'
    END AS day_type,
    COUNT(DISTINCT ord_id) AS total_orders
FROM orders
GROUP BY day_type;

-- SUPPLIER CONTRIBUTION

-- 15.How many suppliers are there in the database?
SELECT COUNT(sup_id) as total_suppliers FROM suppliers;

-- 16. Which supplier provides the most products?
SELECT
    sup_id,
    sup_name,
    total_products
FROM (
    SELECT
        s.sup_id,
        s.sup_name,
        COUNT(p.prod_id) AS total_products,
        ROW_NUMBER() OVER (
            ORDER BY COUNT(p.prod_id) DESC
        ) AS supplier_rank
    FROM suppliers AS s
    JOIN products AS p
        ON s.sup_id = p.sup_id
    GROUP BY s.sup_id, s.sup_name
) AS supplier_ranking
WHERE supplier_rank = 1;

-- 17. What is the average price of products from each supplier?
SELECT sup.sup_id,sup.sup_name,AVG(prod.price) AS avg_price
FROM suppliers AS sup
JOIN products as prod
ON sup.sup_id=prod.sup_id
GROUP BY sup.sup_id,sup.sup_name;

