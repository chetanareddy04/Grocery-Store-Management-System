DELIMITER //

CREATE PROCEDURE GetSupplierRevenue()
BEGIN
SELECT
    s.sup_id,
    s.sup_name,
    SUM(od.total_price) AS total_revenue
FROM suppliers AS s
JOIN products AS p
 ON s.sup_id = p.sup_id
JOIN orderdetails AS od
 ON p.prod_id = od.prod_id
GROUP BY s.sup_id, s.sup_name
ORDER BY total_revenue DESC;
END //

