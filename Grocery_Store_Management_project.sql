CREATE DATABASE grocery_store;
USE grocery_store;

CREATE TABLE suppliers (
    sup_id TINYINT PRIMARY KEY AUTO_INCREMENT,
    sup_name VARCHAR(255),
    address TEXT);
CREATE TABLE categories (
    cat_id TINYINT PRIMARY KEY AUTO_INCREMENT,
    cat_name VARCHAR(255));
CREATE TABLE storeemployees (
    emp_id TINYINT PRIMARY KEY AUTO_INCREMENT,
    emp_name VARCHAR(255),
    hire_date VARCHAR(255));
CREATE TABLE customers (
    cust_id SMALLINT PRIMARY KEY AUTO_INCREMENT,
    cust_name VARCHAR(255),
    address TEXT);
CREATE TABLE products (
    prod_id TINYINT PRIMARY KEY AUTO_INCREMENT,
    prod_name VARCHAR(255),
    sup_id TINYINT,
    cat_id TINYINT,

    price DECIMAL(10,2),

    FOREIGN KEY (sup_id)
        REFERENCES suppliers(sup_id)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    FOREIGN KEY (cat_id)
        REFERENCES categories(cat_id)
        ON UPDATE CASCADE
        ON DELETE CASCADE);
CREATE TABLE orders (
    ord_id SMALLINT PRIMARY KEY AUTO_INCREMENT,
    cust_id SMALLINT,
    emp_id TINYINT,
    order_date VARCHAR(255),

    FOREIGN KEY (cust_id)
        REFERENCES customers(cust_id)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    FOREIGN KEY (emp_id)
        REFERENCES storeemployees(emp_id)
        ON UPDATE CASCADE
        ON DELETE CASCADE);
CREATE TABLE orderdetails (
    ord_detID SMALLINT PRIMARY KEY AUTO_INCREMENT,
    ord_id SMALLINT,
    prod_id TINYINT,
    quantity TINYINT,
    each_price DECIMAL(10,2),
    total_price DECIMAL(10,2),

    FOREIGN KEY (ord_id)
        REFERENCES orders(ord_id)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    FOREIGN KEY (prod_id)
        REFERENCES products(prod_id)
        ON UPDATE CASCADE
        ON DELETE CASCADE);
        
