FROM
    orders
        JOIN
    storeemployees ON orders.emp_id = storeemployees.emp_id;

-- 20.	Which employees have handled the most orders?
SELECT 
    emp_id,
    emp_name,
    (SELECT 
            COUNT(ord_id)
        FROM
            orders
        WHERE
            orders.emp_id = storeemployees.emp_id) AS total_orders_handled
FROM
    storeemployees
ORDER BY total_orders_handled DESC
LIMIT 1;

-- 21. What is the total sales value processed by each employee?
SELECT DISTINCT
    se.emp_id,
    se.emp_name,
    SUM(od.total_price) OVER (
        PARTITION BY se.emp_id
    ) AS total_sales_value
FROM storeemployees AS se
JOIN orders AS o
    ON se.emp_id = o.emp_id
JOIN orderdetails AS od
    ON o.ord_id = od.ord_id;

-- 22.What is the average order value handled per employee?
SELECT
    emp.emp_id,
    emp.emp_name,
    AVG(ov.order_value) AS average_order_value
FROM storeemployees AS emp
JOIN orders AS ord
    ON emp.emp_id = ord.emp_id
JOIN (
    SELECT
        ord_id,
        SUM(total_price) AS order_value
    FROM orderdetails
    GROUP BY ord_id
) AS ov
    ON ord.ord_id = ov.ord_id
GROUP BY emp.emp_id, emp.emp_name;


-- ORDER DETAILS DEEP DIVE
-- 23.	What is the relationship between quantity ordered and total price?
SELECT
    prod_id,
    SUM(quantity) AS total_quantity,
    SUM(total_price) AS total_price,
    CASE
        WHEN SUM(quantity) > 0
        THEN ROUND(SUM(total_price) / SUM(quantity), 2)
        ELSE 0
    END AS average_price_per_unit
FROM orderdetails
GROUP BY prod_id;

-- 24.What is the average quantity ordered per product?
SELECT
    prod.prod_id,
    prod.prod_name,
    a.average_quantity
FROM products AS prod
JOIN (
    SELECT
        prod_id,
        AVG(quantity) AS average_quantity
    FROM orderdetails
    GROUP BY prod_id
) AS a
    ON prod.prod_id = prod.prod_id;

-- 25.	How does the unit price vary across products and orders?
SELECT
    prod.prod_id,
    prod.prod_name,
    ord_det.ord_id,
    ord_det.each_price AS unit_price
FROM products AS prod
JOIN orderdetails AS ord_det
    ON prod.prod_id = ord_det.prod_id
ORDER BY
    prod.prod_id,
    ord_det.ord_id;


    
